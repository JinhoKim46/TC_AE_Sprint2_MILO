"""The store surface the web layer reads and writes (SPEC section 16, D93, D97, D101).

Phase 1a builds against this protocol and an in-memory fake (`milo.web.dev`). Phase 3 wires the real
repositories behind it. Every method that returns owner data takes the signed-in `user_id` (D91).
"""

from __future__ import annotations

from typing import Any, Protocol

Row = dict[str, Any]


class WebStore(Protocol):
    # accounts (D93)
    def authenticate(self, email: str, password: str) -> str | None: ...
    def sign_up(self, email: str, password: str, first_name: str) -> str: ...
    def confirm(self, token: str) -> bool: ...
    def request_reset(self, email: str) -> None: ...
    def reset_password(self, token: str, password: str) -> bool: ...
    def get_user(self, user_id: str) -> Row | None:
        """`id`, `email`, `first_name`, `role`. Re-read on every request (D144)."""

    # consent (D81, D100)
    def has_consent(self, user_id: str, purpose: str) -> bool: ...
    def record_consent(self, user_id: str, purpose: str, version: str) -> None: ...
    def list_consents(self, user_id: str) -> list[Row]: ...

    # sessions and their content (D97 to D102)
    def list_sessions(
        self, user_id: str, *, query: str = "", archived: bool = False
    ) -> list[Row]: ...
    def get_session(self, user_id: str, session_id: str) -> Row | None: ...
    def list_messages(self, user_id: str, session_id: str) -> list[Row]: ...
    def get_spec(self, user_id: str, session_id: str) -> Row | None: ...

    # reports
    def list_reports(self, user_id: str) -> list[Row]: ...
    def get_report(self, user_id: str, report_id: str) -> Row | None: ...

    # operator (D144)
    def ops_submissions(self) -> list[Row]: ...
    def ops_submission(self, submission_id: str) -> Row | None: ...
    def ops_audit(self) -> list[Row]: ...
